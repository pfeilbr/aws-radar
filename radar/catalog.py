"""Service catalog and the matcher that maps source vocabulary to service ids.

The catalog (config/services.yaml) is generated by scripts/build_catalog.py from the AWS
Architecture Icons package plus hand-curated config/service_overrides.yaml.

Matching works on normalized names: lowercase, punctuation to spaces, leading "amazon"/"aws"
dropped. An external name maps to the service whose key equals it, else to the service with
the longest key that is a whole-word prefix of it ("bedrock agent runtime" -> "bedrock",
while "bedrock agentcore" has its own key and wins).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from functools import cached_property

import yaml

from radar import CONFIG_DIR

_DROP_LEADING = {"amazon", "aws", "the"}


def norm(text: str) -> str:
    """'Amazon Simple-Storage_Service (S3)' -> 'simple storage service s3'."""
    t = text.lower().replace("&", " and ")
    t = re.sub(r"[^a-z0-9]+", " ", t).split()
    while t and t[0] in _DROP_LEADING:
        t = t[1:]
    return " ".join(t)


@dataclass
class Service:
    id: str
    name: str
    short: str
    category: str
    icon: str | None = None
    aliases: list[str] = field(default_factory=list)    # extra names / slugs / sdk names
    keywords: list[str] = field(default_factory=list)   # regexes for free-text mentions
    parent: str | None = None


class Catalog:
    def __init__(self, services: list[Service], categories: dict[str, dict]):
        self.services = {s.id: s for s in services}
        self.categories = categories
        self.botocore_names: dict[str, str] = json.loads(
            (CONFIG_DIR / "vocab" / "botocore-services.json").read_text()
        )

    @classmethod
    def load(cls) -> "Catalog":
        raw = yaml.safe_load((CONFIG_DIR / "services.yaml").read_text())
        return cls([Service(**s) for s in raw["services"]], raw["categories"])

    # ── name matching ─────────────────────────────────────────────────────

    @cached_property
    def _keys(self) -> dict[str, str]:
        keys: dict[str, str] = {}
        # Aliases first so they can never be shadowed by an auto-derived name.
        for s in self.services.values():
            for a in s.aliases:
                keys.setdefault(norm(a), s.id)
        for s in self.services.values():
            for k in (s.name, s.short, s.id.replace("-", " ")):
                if norm(k):
                    keys.setdefault(norm(k), s.id)
        return keys

    def match_name(self, text: str) -> str | None:
        n = norm(text)
        if not n:
            return None
        if n in self._keys:
            return self._keys[n]
        words = n.split()
        for i in range(len(words) - 1, 0, -1):
            prefix = " ".join(words[:i])
            if prefix in self._keys:
                return self._keys[prefix]
        return self._compact_keys.get(n.replace(" ", ""))

    @cached_property
    def _compact_keys(self) -> dict[str, str]:
        out: dict[str, str] = {}
        for k, sid in self._keys.items():
            out.setdefault(k.replace(" ", ""), sid)
        return out

    def match_botocore(self, sdk_name: str) -> str | None:
        """'s3control' / 'bedrock-agent-runtime' -> service id."""
        if sdk_name in self._keys:  # exact alias like 's3control'
            return self._keys[sdk_name]
        return (
            self.match_name(sdk_name.replace("-", " "))
            or self.match_name(self.botocore_names.get(sdk_name, ""))
        )

    # ── free-text mentions ────────────────────────────────────────────────

    @cached_property
    def _text_patterns(self) -> list[tuple[re.Pattern, str]]:
        """Regexes for spotting services in titles/summaries, most specific first."""
        pats: list[tuple[str, str, bool]] = []
        for s in self.services.values():
            # The official full name ("Amazon Bedrock", "AWS Lambda") is always safe.
            pats.append((re.escape(s.name), s.id, False))
            # Curated keywords are case-sensitive regexes ("S3", "Lambda\\b", "EKS").
            for kw in s.keywords:
                pats.append((kw, s.id, True))
        pats.sort(key=lambda p: -len(p[0]))
        out = []
        for pat, sid, case in pats:
            flags = 0 if case else re.I
            out.append((re.compile(rf"(?<![\w-])(?:{pat})(?![\w-])", flags), sid))
        return out

    def match_text(self, text: str) -> list[str]:
        found: list[str] = []
        spans: list[tuple[int, int]] = []
        for rx, sid in self._text_patterns:
            for m in rx.finditer(text):
                a, b = m.span()
                if any(a < y and x < b for x, y in spans):
                    continue  # already claimed by a longer, more specific name
                spans.append((a, b))
                if sid not in found:
                    found.append(sid)
        return found
